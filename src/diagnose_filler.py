import sys
import os

sys.path.append(os.path.join(os.path.dirname(__file__), "..", "features"))
from features.detectors.filler_detector import FillerDetector


def diagnose(text: str) -> None:
    tokens = text.split()
    print(f"총 토큰 수: {len(tokens)}")

    # 1) 사전에 정확히 없더라도, "필러처럼 보이는" 후보를 넓게 잡아 눈으로 확인
    #    (실제 사전 매칭과 무관하게, 짧은 1~2글자 토큰만 따로 뽑아본다)
    short_tokens = [(i, t) for i, t in enumerate(tokens) if len(t) <= 2]
    print(f"\n1~2글자 짧은 토큰 후보 ({len(short_tokens)}개) — 필러가 여기 섞여 있는지 확인:")
    for i, t in short_tokens[:30]:
        print(f"  위치 {i:3d}: '{t}'  (repr: {t!r})")  # repr로 보이지 않는 문장부호/공백 확인

    # 2) 실제 FillerDetector 결과
    detector = FillerDetector()
    result = detector.detect(tokens)
    print(f"\nFillerDetector 탐지 결과: {result}")

    # 3) 사전에 있는 단어가 텍스트 안에 '부분 문자열'로라도 존재하는지 확인
    #    (완전 일치는 실패했지만 구두점 등으로 인해 포함은 되어 있는 경우 파악)
    print("\n사전 단어가 텍스트에 부분 문자열로라도 등장하는지:")
    for word in detector.lexicon:
        found = [t for t in tokens if word in t]
        if found:
            print(f"  '{word}' 포함된 토큰: {found}")


